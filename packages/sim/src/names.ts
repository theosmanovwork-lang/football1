function capitalize(text: string): string {
  return text.charAt(0).toUpperCase() + text.slice(1)
}

export function personName(rng: Rng, style: NameStyle): { firstName: string; lastName: string } {
  return {
    firstName: rng.pick(style.given),
    lastName: capitalize(rng.pick(style.surnameStart) + rng.pick(style.surnameEnd)),
  }
}

export function townName(rng: Rng, style: NameStyle): string {
  const start = rng.pick(style.townStart)
  let end = rng.pick(style.townEnd)
  // Avoid stutters like "Ауау" or "Монмон".
  while (start.toLowerCase().replace('-', '') === end.toLowerCase()) end = rng.pick(style.townEnd)
  // "Сан-" + "мора" → "Сан-Мора": capitalize the part after a hyphen.
  return start.endsWith('-') ? start + capitalize(end) : capitalize(start + end)
}
